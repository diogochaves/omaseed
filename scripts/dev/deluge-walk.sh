cleanup() {
    local status=$?
    # A daemon the walk slowed is let go whatever happened; so is its own peer.
    [ -z "$THROTTLE" ] || kill "$THROTTLE" 2>/dev/null || true
    [ -z "$SAMPLER" ] || kill "$SAMPLER" 2>/dev/null || true
    [ -z "$PEER_PID" ] || kill "$PEER_PID" 2>/dev/null || true
    local pid
    pid="$(deluged_pid)"
    [ -z "$pid" ] || kill -CONT "$pid" 2>/dev/null || true
    if [ "$INTERACTIVE" = 1 ]; then
        echo
        echo "The box stays up for a look around; throw it away with: scripts/dev/app-box.sh down -b $BOX"
        [ "$STARTED" = 0 ] || echo "The playground stays up too: scripts/dev/test-server.sh reset|stop --deluge"
    else
        "$APP_BOX" down -b "$BOX" >/dev/null 2>&1 || true
        if [ "$STARTED" = 1 ]; then
            "$TEST_SERVER" stop --deluge >/dev/null 2>&1 || true
            [ ! -d "$LOCKED" ] || chmod u+w "$LOCKED"
            [ ! -d "$READONLY" ] || chmod u+w "$READONLY"
            rm -rf "${PROFILE:?}"
        else
            # Put back what the walk turned off or changed on a playground it found running.
            dcall web.connect "[\"$DAEMON_ID\"]" >/dev/null 2>&1 || true
            dcall core.enable_plugin '["Label"]' >/dev/null 2>&1 || true
            [ -z "$OVERHEAD" ] || dcall core.set_config "[{\"rate_limit_ip_overhead\": $OVERHEAD}]" >/dev/null 2>&1 || true
            remove_walk_torrents
        fi
    fi
    rm -rf "$SCRATCH"
    exit "$status"
}
