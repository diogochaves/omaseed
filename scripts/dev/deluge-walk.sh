# omaseed — a Deluge server driven through the app (#87's "done when", DECISIONS C14 E6, C25):
# first contact with a deluge-web that has no daemon, and the server sheet's daemon step (K10)
# that connects it; a .torrent added through the add sheet with a label and a save path; a
# magnet's files read from Deluge's prefetch before the add; a rename (K28: only the shown
# name, the folder keeps its own); a new label (lower case, K15) and the label taken off; the
# Label plugin turned off on the daemon (the labels go, C says why) and on again; a ratio limit
# that removes; a move, and a big one copied while Deluge reports its % (K21); the move Deluge
# drops without a word (only its own log says why: read as failed and never sent again); a move Deluge fails
# with an error, which pauses the torrent until a recheck, and the recheck that clears it (K24);
# one Settings › Deluge switch written and read back on the daemon, then put back; and a delete
# with its files. After each step it checks what the daemon says (deluge-web's /json) and
# what is on disk, and stops at the first mismatch.
#
#   scripts/dev/deluge-walk.sh [OUT_DIR]       # agents: a headless box, a shot per step,
#                                              # OUT_DIR/index.md lists every check
#   scripts/dev/deluge-walk.sh --interactive   # a person: the box is a window on workspace 9;
#                                              # each step waits for enter
#
# The server is the Deluge playground (scripts/dev/test-server.sh start --deluge: deluged and
# deluge-web on :8086, its profile under ~/.local/share/omaseed-test/deluge, the password
# DELUGE_TEST_PASS in ~/.config/omaseed/dev.env). When it isn't running, the walk starts it,
# seeds it (three small torrents that must come through untouched) and, at the end, stops it
# and wipes its profile; when it is, the walk leaves it running and takes away only what it
# made (its torrents with their data, its labels, its folders) and puts back what it turned
# off. The torrents under test are made here from generated bytes with transmission-create,
# their data put where they are added. The magnet's files come from a peer of the walk's own
# (scripts/dev/metadata-peer.py, on 127.0.0.1, named in the magnet): no tracker, no DHT. The box
# (scripts/dev/app-box.sh up --deluge) reaches only :8086; deluged runs on this machine, so
# the paths typed into the app are this machine's, under the profile. The big move copies to a
# btrfs subvolume beside its folder, with deluged slowed (stopped 0.9 s of every 0.95 s) so its
# % can be seen; where the profile isn't on btrfs it is a rename and that part is skipped.
