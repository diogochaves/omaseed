cat >"$SCRATCH/dclient.py" <<'PY'
import http.cookiejar, json, os, sys, time, urllib.request

URL = os.environ["DE_JSON"]


def password():
    if os.environ.get("DELUGE_TEST_PASS"):
        return os.environ["DELUGE_TEST_PASS"]
    path = os.environ.get("DEV_ENV", "")
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if line.startswith("export "):
            line = line[7:].strip()
        if line.startswith("DELUGE_TEST_PASS="):
            return line.split("=", 1)[1].strip().strip("'\"")
    raise SystemExit("no DELUGE_TEST_PASS")


opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(http.cookiejar.CookieJar()))


def call(method, params, timeout=15):
    body = json.dumps({"method": method, "params": params, "id": 1}).encode()
    request = urllib.request.Request(URL, body, {"Content-Type": "application/json"})
    with opener.open(request, timeout=timeout) as reply:
        answer = json.load(reply)
    if answer.get("error"):
        raise SystemExit("%s: %s" % (method, answer["error"]))
    return answer["result"]


if not call("auth.login", [password()]):
    raise SystemExit("deluge-web refuses DELUGE_TEST_PASS")
if sys.argv[1] == "--sample":
    with open(sys.argv[3], "a", encoding="utf-8") as out:
        while True:
            try:
                t = call("core.get_torrent_status", [sys.argv[2], ["state", "progress", "save_path"]])
                out.write("%s %.1f %s\n" % (t.get("state"), t.get("progress", -1), t.get("save_path")))
                out.flush()
            except Exception as error:  # a slowed daemon may time out: keep sampling
                out.write("? %s\n" % error)
            time.sleep(0.25)
print(json.dumps(call(sys.argv[1], json.loads(sys.argv[2]) if len(sys.argv) > 2 else [])))
PY
export DEV_ENV
dcall() { python3 -I "$SCRATCH/dclient.py" "$@"; }

FIELDS='["name","label","save_path","state","progress","message","paused","total_done","total_size","stop_at_ratio","stop_ratio","remove_at_ratio","files"]'

# tq HASH EXPR: a Python expression over `t`, the torrent HASH as the daemon lists it now
# (None once it is gone), and `every`, all of them (each with its `hash`).
tq() {
    dcall core.get_torrents_status "[{}, $FIELDS]" | python3 -c '
import json, sys
listed = json.load(sys.stdin)
every = [dict(v, hash=k) for k, v in listed.items()]
t = listed.get(sys.argv[1])
print(eval(sys.argv[2]))' "$1" "$2"
}

# dq EXPR: a Python expression over `r`, the result of `dcall METHOD PARAMS`.
dq() {
    dcall "$2" "${3:-[]}" | python3 -c 'import json, sys; r = json.load(sys.stdin); print(eval(sys.argv[1]))' "$1"
}

# The outcome strip's line runs down for 6 s at the table's bottom (DECISIONS C18 D3): the
# waits leave its band of the screen out, as the actions walk does.
STRIP_IGNORE="0,920 1920,110"
keys() { omabox keys -b "$BOX" --window omaseed --wait --ignore "$STRIP_IGNORE" "$@" >/dev/null 2>&1 || true; }

# menu_on QUERY: the jump palette's tab: the cursor on the torrent QUERY finds, its actions
# menu open. table_on QUERY: the same, the menu closed again, the keyboard on the table.
menu_on() { keys ctrl+k -t "$1" Tab; }
table_on() { menu_on "$1"; keys Escape; }

# short TEXT: TEXT with the profile's path written PROFILE, as the index says.
short() { printf '%s' "${1//"$PROFILE"/PROFILE}"; }

CHECKS=0
STEP=0
STEP_SLUG=""

fail() {
    set -- "$(short "$1")"
    printf '  \033[31m✗ %s\033[0m\n' "$1"
    if [ "$INTERACTIVE" = 0 ]; then
        printf '  - ✗ **%s**\n' "$1" >>"$OUT/index.md"
        omabox shot -b "$BOX" -o "$OUT/failed.png" >/dev/null 2>&1 || true
        printf '\n**Stopped here.** ![](failed.png)\n' >>"$OUT/index.md"
        echo "FAIL after $CHECKS checks: $OUT/index.md"
    fi
    exit 1
}

pass() {
    CHECKS=$((CHECKS + 1))
    set -- "$(short "$1")"
    printf '  ✓ %s\n' "$1"
    [ "$INTERACTIVE" = 1 ] || printf '  - ✓ %s\n' "$1" >>"$OUT/index.md"
}

# expect "WHAT" HASH EXPR [SECONDS]: wait until EXPR (see tq) is True for HASH.
expect() {
    local what="$1" hash="$2" expr="$3" limit="${4:-20}" got=""
    for _ in $(seq 1 $((limit * 4))); do
        got="$(tq "$hash" "$expr" 2>&1 || true)"
        [ "$got" = True ] && { pass "$what"; return 0; }
        sleep 0.25
    done
    fail "$what (after ${limit}s: $expr is ${got:-nothing})"
}

# expect_call "WHAT" EXPR METHOD [PARAMS] [SECONDS]: wait until EXPR over `r` (see dq) is True.
expect_call() {
    local what="$1" expr="$2" method="$3" params="${4:-[]}" limit="${5:-20}" got=""
    for _ in $(seq 1 $((limit * 4))); do
        got="$(dq "$expr" "$method" "$params" 2>&1 || true)"
        [ "$got" = True ] && { pass "$what"; return 0; }
        sleep 0.25
    done
    fail "$what (after ${limit}s: $expr over $method is ${got:-nothing})"
}

# expect_disk "WHAT" TEST PATH [SECONDS]: wait until `test TEST PATH` holds here (the daemon's
# disk is this machine's); TEST `!` waits until nothing is at PATH.
expect_disk() {
    local what="$1" op="$2" path="$3" limit="${4:-20}"
    for _ in $(seq 1 $((limit * 4))); do
        if [ "$op" = "!" ]; then
            [ ! -e "$path" ] && { pass "$what"; return 0; }
        else
            test "$op" "$path" && { pass "$what"; return 0; }
        fi
        sleep 0.25
    done
    fail "$what (after ${limit}s: test $op ${path#"$HOME"/} is false)"
}

# expect_same "WHAT" SOURCE PATH: the file PATH holds the bytes the torrent was made from.
expect_same() {
    if cmp -s "$WALK/src/$2" "$3"; then pass "$1"; else fail "$1 (${3#"$HOME"/} differs or is missing)"; fi
}

# expect_text "WHAT" TEXT [SECONDS]: wait until omaseed's window shows TEXT (its
# accessibility tree has a node holding it).
expect_text() {
    if omabox wait -b "$BOX" --timeout "${3:-20}s" tree "$2" --window omaseed >/dev/null 2>&1; then
        pass "$1"
    else
        fail "$1 (after ${3:-20}s no \"$2\" in the window)"
    fi
}

# expect_no_text "WHAT" TEXT [SECONDS]: wait until omaseed's window no longer shows TEXT.
expect_no_text() {
    if omabox wait -b "$BOX" --timeout "${3:-20}s" tree "$2" --window omaseed --gone >/dev/null 2>&1; then
        pass "$1"
    else
        fail "$1 (after ${3:-20}s \"$2\" is still in the window)"
    fi
}

# expect_node "WHAT" PATTERN: a line of the window's tree matches PATTERN (grep -E): a node's
# role, name and state, e.g. 'button "test" \[focused'.
expect_node() {
    if omabox tree -b "$BOX" --window omaseed 2>/dev/null | grep -qE -- "$2"; then
        pass "$1"
    else
        fail "$1 (no node matching $2 in the window)"
    fi
}

# expect_gone_but "WHAT" TEXT BUT [SECONDS]: wait until no node of omaseed's window holds
# TEXT, leaving out the nodes that also hold BUT.
expect_gone_but() {
    local what="$1" text="$2" but="$3" limit="${4:-20}"
    for _ in $(seq 1 "$limit"); do
        if ! omabox tree -b "$BOX" --window omaseed 2>/dev/null | grep -F -- "$text" | grep -qvF -- "$but"; then
            pass "$what"
            return 0
        fi
        sleep 1
    done
    fail "$what (after ${limit}s a node still holds \"$text\")"
}

# step "TITLE" "WHAT IT DOES": interactive, say it and wait for enter; headless, a heading.
step() {
    STEP=$((STEP + 1))
    STEP_SLUG="$(printf '%02d' "$STEP")-$(echo "$1" | tr 'A-Z ' 'a-z-' | tr -cd 'a-z0-9-')"
    set -- "$1" "$(short "$2")"
    printf '\n\033[1m%02d %s\033[0m\n    %s\n' "$STEP" "$1" "$2"
    if [ "$INTERACTIVE" = 1 ]; then
        printf '    enter to do it '
        read -r _
    else
        printf '\n### %02d %s\n\n%s\n\n' "$STEP" "$1" "$2" >>"$OUT/index.md"
    fi
}

# shot "WHAT TO SEE" [SUFFIX]: headless, the app's window into OUT and index.md.
shot() {
    [ "$INTERACTIVE" = 0 ] || return 0
    local file="$STEP_SLUG${2:+-$2}.png"
    omabox shot -b "$BOX" --window omaseed -o "$OUT/$file" >/dev/null 2>&1
    printf '  ![%s](%s)\n  *%s*\n' "$file" "$file" "$(short "$1")" >>"$OUT/index.md"
}

# note TEXT: a line in index.md (and on the terminal) that is not a check.
note() {
    printf '  (%s)\n' "$(short "$1")"
    [ "$INTERACTIVE" = 1 ] || printf '\n*%s*\n' "$(short "$1")" >>"$OUT/index.md"
}

infohash() { transmission-show "$1" | sed -n 's/^ *Hash v1: *//p'; }
deluged_pid() { cut -d';' -f1 "$PROFILE/omaseed-deluged.pid" 2>/dev/null; }
moves_logged() { grep -c "Could not move storage for torrent $1" "$PROFILE/deluged.log" 2>/dev/null || true; }

# remove_walk_torrents: whatever a run left on the daemon (a torrent named Walk Sampler…, Walk
# Magnet or walk-big), removed with its data; the walk's labels; the walk's folders.
remove_walk_torrents() {
    local hash
    for hash in $(dcall core.get_torrents_status '[{}, ["name"]]' 2>/dev/null | python3 -c '
import json, sys
for h, t in json.load(sys.stdin).items():
    if t["name"].startswith(sys.argv[1]) or t["name"] in sys.argv[2:]:
        print(h)' "$NAME" "$MAGNET_NAME" "$BIG" 2>/dev/null || true); do
        dcall core.remove_torrent "[\"$hash\", true]" >/dev/null 2>&1 || true
    done
    dcall label.remove '["walk-label"]' >/dev/null 2>&1 || true
    dcall label.remove '["walk-two"]' >/dev/null 2>&1 || true
    [ ! -d "$LOCKED" ] || chmod u+w "$LOCKED"
    [ ! -d "$READONLY" ] || chmod u+w "$READONLY"
    # FAR may be a btrfs subvolume: rm empties it and removes it as a folder (Linux 4.18+).
    rm -rf "${WALK:?}"
}

STARTED=0
