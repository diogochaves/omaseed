        case "$1" in
        "$PROFILE/downloads" | "$PROFILE/downloads"/*) echo "/downloads${1#"$PROFILE/downloads"}"; return ;;
        "$PROFILE/far" | "$PROFILE/far"/*) echo "/far${1#"$PROFILE/far"}"; return ;;
        esac
    fi
    echo "$1"
}
